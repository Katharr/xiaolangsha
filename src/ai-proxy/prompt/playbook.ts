/**
 * L3 阵营打法：按 `vi.ownFaction` 条件装配（好人 / 狼人，互不出现对方的专属内容）。
 * 这里讲的是「拿到这一边该怎么打的原则」，承接 L2 的判读知识落到行动倾向上。
 *
 * 红线：
 * - 仍不得出现 `狼人是` / `预言家是` 断言子串。
 * - 条件装配可测：好人段含「保护真预言家」且不含狼专属词（如「悍跳」）；狼段反之。
 */
import type { VisibleInformationSnapshot } from "../../shared";

/** 好人打法：首要找出并保护真预言家、采信无对跳的单跳查杀（直接修首夜冤神 bug）。 */
export function goodPlaybook(): string {
  return [
    "你坐在好人这边。你的头等大事：找出并保护真预言家，靠验人信息去推狼，而不是靠互相猜。",
    "当场上只有一个人跳预言家、没有第二个人对跳时，他报出的查杀就是此刻最强的信息——你应当采信它、把票跟上去归到那个被查杀的人身上，而不是因为「他跳得太急、太自信」反过来怀疑他。把真预言家当狼推，等于替狼杀掉好人的信息源。",
    "只有当出现对跳（两个人都争预言家、互指对方假）时，你才进入辨真假模式，去比对双方的验人逻辑、归票和破绽，把票投向你判断为假的那一个。",
    "即便你天生多疑，那份多疑也用在普通玩家身上——别把一个无人对跳的孤身查杀当成破绽来打。",
    "如果你自己就是神职，既要适时产出信息帮好人定位狼，也要顾着自保，别轻易把自己暴露成狼刀的靶子。",
  ].join("\n");
}

/** 狼人打法：屠边、护队友、必要时悍跳/对跳转移火力、伪装成真好人。叠加队友名单。 */
export function werewolfPlaybook(vi: VisibleInformationSnapshot): string {
  const teammateLine =
    vi.teammates.length > 0
      ? `你的狼队友：${vi.teammates
          .map((t) => `${t.name}（${t.seat}号，${t.alive ? "存活" : "已出局"}）`)
          .join(
            "、",
          )}。他们和你是一伙的，绝不要查杀、归票或投票针对自己的队友；白天要不动声色地帮队友洗清嫌疑、把火引到好人身上，狼刀尽量集中在同一个目标上。`
      : "这局你是独狼，没有狼队友，更要靠伪装和带节奏一个人扛。";

  return [
    "你坐在狼这边。目标是屠边——优先消耗好人的神职，把局势推向己方获胜的那一边。",
    teammateLine,
    "必要时你可以悍跳预言家（冒充预言家、报一个假查验）去顶替真信息源，也可以扛推、对跳，把火力从队友身上引开。",
    "装得像个真好人：别因为你知道场上的真相，就把话说得「过度准确」，那反而会露马脚——按一个正常好人会有的认知去发言。",
  ].join("\n");
}

/** 按阵营选打法段。 */
export function factionPlaybook(vi: VisibleInformationSnapshot): string {
  return vi.ownFaction === "werewolf_team"
    ? werewolfPlaybook(vi)
    : goodPlaybook();
}
