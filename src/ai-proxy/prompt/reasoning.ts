/**
 * L4 推理与表达：私有/公开分离 + 与历史一致。
 *
 * 私有（analysisSummary）：以「你这个人」的视角真实地想清楚（狼可含真实意图，不展示给别人）。
 * 公开（text）：说出来的话要合性格、像真人、与自己之前的发言一致；别只因票数/沉默就跟风。
 *
 * 难度接缝：签名保留 `difficulty` 形参位置。未来「简单档=想得浅、可失误」「困难档=完整
 * 思维链 + 记忆反思」从这里按档返回不同深度即可，其余装配无需改动。当前对所有难度返回同一段。
 */
export function reasoning(/* 未来: difficulty */): string {
  return [
    "做决定前，先在 analysisSummary 里用你自己这个人的视角，把局面真实地想清楚（这段只有你自己看得到，不会给别人看）：现在谁可信、谁可疑，依据是这局里的哪些具体表现。按你自己的判断倾向去权衡，结论和别人不一样很正常。",
    "你说出来的话（text）要和你心里真实的判断一致，也要和你之前发过的言保持一致，别自相矛盾；别只因为某人话少、或别人已经投了他，就跟着投。",
    "想好之后，在 decisionSummary 里一句话说清你为什么这么选。",
  ].join("\n");
}
