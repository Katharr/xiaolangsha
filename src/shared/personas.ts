/** 按名字取判断倾向；未知名字回退一句中性倾向，绝不抛错（仿 personaForName）。 */
export function dispositionForName(name: string): string {
  return NAME_DISPOSITIONS[name] ?? "综合各方面线索、不偏向某一种判断方式";
}
