  花花: "信第一直觉：相信临场那种「感觉不对劲」，不爱在细枝末节上反复纠结",
  老张: "谨慎压票：先压住判断、多听一两轮再表态，最怕冤枉好人",
  莉莉: "天生多疑：默认人人都有嫌疑，要看到干净的表现才肯收回怀疑",
  大壮: "看重票型：很在意场上多数人往哪站，倾向顺着票型集中的方向走",
  囡囡: "倾向信任：默认先给人信任，除非出现明显破绽才翻脸改判",
